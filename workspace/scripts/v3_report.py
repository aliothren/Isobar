"""V3 aggregation: every unit's configs into one table, the global
distribution of gains, the catalog of cases, the scaling tables, the E3
and E5 summaries, the main-case candidates and the figure data index.

    python3 scripts/v3_report.py            -> analysis/v3/all_configs.csv, REPORT.md, confirm_specs.json
"""
import csv
import glob
import json
import os
import statistics
import sys

WS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V3 = os.path.join(WS, "analysis", "v3")
UNITS = ("e0", "e1a", "e1t", "e1s", "e1b", "e2_depth", "e2_width", "e2_ffn", "e4", "confirm")


def load_all():
    rows = []
    for u in UNITS:
        p = os.path.join(V3, u, "configs.jsonl")
        if not os.path.exists(p):
            continue
        for l in open(p):
            r = json.loads(l); r["unit"] = u; rows.append(r)
    return rows


def flat(r):
    s = r["spec"]
    base = {"unit": r["unit"], "config_id": r["config_id"], "status": r["status"], "d": s["d"], "dh": s["dh"], "d_ff": s["d_ff"],
            "ratio": s["d_ff"] / s["d"], "L": s["L"], "S": s["S"], "phase": s["phase"], "tiling": s["tiling"], "topology": s["topology"],
            "routing": s["routing"], "kappa": s["kappa"], "bw": s["bw"]}
    if r["status"] != "done":
        base["reason"] = r.get("reason", ""); return base
    m, sr, b, t = r["metrics"], r["search"], r["band"], r["timing"]
    h = sr["runs"][sr["headline"]]
    bind = {}
    base.update({"account": r["account_status"], "grid": "x".join(map(str, r["grid"])), "n_dies": r["n_dies"], "empty_slots": r["empty_slots"],
                 "strongest": r["strongest"], "strongest_is_random": r["strongest"].startswith("random_s"), "strongest_rule": r["strongest_rule"],
                 "T_base_ms": r["T_base_s"] * 1e3, "random_median_ms": r["random_median_s"] * 1e3, "random_spread_pct": r["random_spread_pct"],
                 "steps": sr["steps"], "headline_T_ms": sr["headline_T_s"] * 1e3, "G_median": sr["gain_median_pct"], "G_min": sr["gain_min_pct"],
                 "G_max": sr["gain_max_pct"], "G_best": sr["gain_best_pct"], "G_range": sr["gain_max_pct"] - sr["gain_min_pct"],
                 "eta": m["eta_comm"] * 100, "r0": m["r0"] * 100, "g_bw_eq": (m["g_bw_eq"] or 0) * 100, "B_eq": m["B_eq_gbps"],
                 "G_vs_default": m["gain_vs_default_pct"], "G_vs_rule": m["gain_vs_strongest_rule_pct"], "dE": m["dE_pct"], "dE_comm": m["dE_comm_pct"],
                 "B_minus": b["rules"]["B_minus"], "B_plus": b["rules"]["B_plus"], "band_ratio": b["rules"]["ratio"],
                 "band_ratio_pool": b["rules_plus_pool"]["ratio"], "region_at_bw": ("below" if s["bw"] < b["rules"]["B_minus"] else "above" if s["bw"] > b["rules"]["B_plus"] else "inside"),
                 "invariant": r["ordering_invariant_over_grid"], "full_score_ms": t["full_score_ms"], "ms_per_step": t["ms_per_sa_step_median"],
                 "config_wall_s": t["config_wall_s"], "rule_failures": ",".join(r.get("rule_failures", {}).keys())})
    return base


def q(xs, p):
    xs = sorted(xs); k = (len(xs) - 1) * p; f = int(k); c = min(f + 1, len(xs) - 1)
    return xs[f] + (xs[c] - xs[f]) * (k - f)


def main():
    rows = [flat(r) for r in load_all()]
    done = [r for r in rows if r["status"] == "done"]
    keys = sorted({k for r in rows for k in r}, key=lambda k: (k not in ("unit", "config_id", "status"), k))
    with open(os.path.join(V3, "all_configs.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.4f}" if isinstance(v, float) else v) for k, v in r.items()})
    md = ["# V3 campaign report (auto-generated by scripts/v3_report.py)\n"]
    md.append(f"Configs: {len(rows)} planned, {len(done)} done, {len(rows) - len(done)} infeasible. Table: `all_configs.csv`.\n")
    # distributions
    def dist(name, xs):
        if not xs:
            return f"| {name} | 0 | | | | | |"
        return f"| {name} | {len(xs)} | {min(xs):.2f} | {q(xs, 0.25):.2f} | {statistics.median(xs):.2f} | {q(xs, 0.75):.2f} | {max(xs):.2f} |"
    md.append("## Distribution over all done configs (percent)\n")
    md.append("| quantity | n | min | q25 | median | q75 | max |"); md.append("|---|---|---|---|---|---|---|")
    for k, lab in (("G_median", "G end-to-end (median seed) vs strongest baseline"), ("eta", "eta_comm"), ("r0", "communication share r0"),
                   ("g_bw_eq", "bandwidth equivalence g_BW"), ("G_vs_default", "G vs default fill"), ("dE", "dynamic energy change"),
                   ("band_ratio", "band ratio B+/B- (7 rules)"), ("G_range", "seed range of G")):
        md.append(dist(lab, [r[k] for r in done if r.get(k) is not None]))
    md.append("\n## Per unit\n")
    md.append("| unit | done | G median of medians | G min | G max | eta median | r0 median | strongest is random (share) |"); md.append("|---|---|---|---|---|---|---|---|")
    for u in UNITS:
        xs = [r for r in done if r["unit"] == u]
        if not xs:
            continue
        md.append(f"| {u} | {len(xs)} | {statistics.median(r['G_median'] for r in xs):.2f} | {min(r['G_median'] for r in xs):.2f} | {max(r['G_median'] for r in xs):.2f} | "
                  f"{statistics.median(r['eta'] for r in xs):.1f} | {statistics.median(r['r0'] for r in xs):.1f} | {sum(r['strongest_is_random'] for r in xs) / len(xs):.2f} |")
    # winners
    md.append("\n## Which baseline is the strongest, and which named rule wins\n")
    from collections import Counter
    c1 = Counter("random" if r["strongest_is_random"] else r["strongest"] for r in done)
    c2 = Counter(r["strongest_rule"] for r in done)
    md.append("strongest baseline: " + ", ".join(f"{k} {v}" for k, v in c1.most_common()))
    md.append("\nstrongest named rule: " + ", ".join(f"{k} {v}" for k, v in c2.most_common()) + "\n")
    # catalog
    md.append("## Catalog\n")
    def table(title, xs):
        md.append(f"### {title}\n")
        md.append("| config | dies | grid | kappa | strongest | T_base (ms) | G median [min, max] | eta | r0 | g_BW | region | account |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in xs:
            md.append(f"| {r['config_id']} | {r['n_dies']} | {r['grid']} | {r['kappa']} | {r['strongest']} | {r['T_base_ms']:.1f} | {r['G_median']:.2f} [{r['G_min']:.2f}, {r['G_max']:.2f}] | "
                      f"{r['eta']:.1f} | {r['r0']:.1f} | {r['g_bw_eq']:.1f} | {r['region_at_bw']} | {r['account'][:28]} |")
        md.append("")
    srt = sorted(done, key=lambda r: -r["G_median"])
    table("Highest end-to-end gains", srt[:15])
    table("Lowest / zero / negative gains", srt[-15:])
    table("Largest communication improvements (eta)", sorted(done, key=lambda r: -r["eta"])[:10])
    inv = [r for r in done if not r["invariant"]]
    table("Ordering not invariant over the rate x bandwidth grid (should be empty under the separable model)", inv)
    rf = [r for r in done if r["rule_failures"]]
    md.append(f"Configs where a named rule could not tile the grid: {len(rf)} (" + ", ".join(sorted({r['rule_failures'] for r in rf})) + ")\n")
    # scaling tables
    for u, lab in (("e2_depth", "Depth scaling (d 2560, ratio 4)"), ("e2_width", "Width scaling (L 32, ratio 4)"), ("e2_ffn", "FFN ratio scaling (d 2560, L 32)"), ("e1s", "Workpoints (S, phase) on the reference model"), ("e4", "Tiling variants"), ("e1t", "Topologies")):
        xs = [r for r in done if r["unit"] == u]
        if not xs:
            continue
        md.append(f"## {lab}\n")
        md.append("| config | d | dh | ratio | L | S | phase | tiling | dies | grid | empty | r0 | eta | G median [min,max] | g_BW | band | T_base (ms) | full score (ms) | search wall (s) | account |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in sorted(xs, key=lambda r: (r["d"], r["ratio"], r["L"], r["S"], r["grid"])):
            md.append(f"| {r['config_id']} | {r['d']} | {r['dh']} | {r['ratio']:g} | {r['L']} | {r['S']} | {r['phase']} | {r['tiling']} | {r['n_dies']} | {r['grid']} | {r['empty_slots']} | {r['r0']:.1f} | {r['eta']:.1f} | "
                      f"{r['G_median']:.2f} [{r['G_min']:.2f},{r['G_max']:.2f}] | {r['g_bw_eq']:.1f} | {r['band_ratio']:.2f} | {r['T_base_ms']:.1f} | {r['full_score_ms']:.1f} | {r['config_wall_s']:.0f} | {r['account'][:24]} |")
        md.append("")
        inf = [r for r in rows if r["unit"] == u and r["status"] != "done"]
        if inf:
            md.append("Infeasible: " + "; ".join(f"{r['config_id']}: {r['reason']}" for r in inf) + "\n")
    # E3
    p = os.path.join(V3, "e3_k2", "discriminability.json")
    if os.path.exists(p):
        d = json.load(open(p))
        md.append("## E3 discriminability at the main port ratio (analytic kappa 2; BookSim at concentration 4 with wavefront allocators; reference = BookSim cycles where available, else the full model). The kappa = 1 corner runs are in `e3/`.\n")
        md.append("| scenario | n | reference | rho A_full | rho A_links | rho word_hops | rho max_hops | inversions A_full | inversions word_hops | exact tie groups word_hops (n, largest, max ref span) | exact tie groups max_hops | regret word_hops pick | BookSim/bound (min, med, max) |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for s, a in d.items():
            if "correlations" not in a:
                continue
            c, i, tg, sr = a["correlations"], a["inversions"], a["tie_groups"], a["selection_regret"]
            f = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v)
            twh, tmh = tg["word_hops"]["tol0"], tg["max_hops"]["tol0"]
            bb = a.get("booksim_over_bound")
            md.append(f"| {s} | {a['n']} | {a['reference']} | {f(c['A_full'])} | {f(c['A_links'])} | {f(c['word_hops'])} | {f(c['max_hops'])} | {f(i['A_full'])} | {f(i['word_hops'])} | "
                      f"{twh['n_groups']}, {twh['largest']}, {twh['ref_span_max']*100:.1f}% | {tmh['n_groups']}, {tmh['largest']}, {tmh['ref_span_max']*100:.1f}% | "
                      f"{sr['word_hops']['regret_min']*100:.1f} to {sr['word_hops']['regret_max']*100:.1f}% | " + (f"{bb['min']:.2f}, {bb['median']:.2f}, {bb['max']:.2f}" if bb else "") + " |")
        md.append("")
    for f_ in sorted(glob.glob(os.path.join(V3, "e3_k2", "ablation_*.json"))) + sorted(glob.glob(os.path.join(V3, "e3", "ablation_ref_k*.json"))):
        d = json.load(open(f_))
        for name, rec in d.items():
            md.append(f"### Ablation {name}: strongest {rec['strongest']}, {rec.get('n_dies', '')} dies, steps {rec.get('steps', 1200)}\n")
            md.append("| objective | gain median vs strongest | overhead vs full (median) | overhead vs full (best) | BookSim gain vs strongest | BookSim overhead vs full |"); md.append("|---|---|---|---|---|---|")
            for k, v in rec["summary"].items():
                md.append(f"| {k} | {v['gain_median_pct']:.2f}% | {v['overhead_vs_full_median_pct']:+.2f}% | {v.get('overhead_vs_full_best_pct', float('nan')):+.2f}% | "
                          f"{v.get('booksim_gain_vs_strongest_pct', float('nan')):.2f}% | {v.get('booksim_overhead_vs_full_pct', float('nan')):+.2f}% |")
            md.append("")
    # E5
    p = os.path.join(V3, "e5", "timing.json")
    if os.path.exists(p):
        d = json.load(open(p))
        md.append(f"## E5 timing ({d['environment']['cpu']}, load at start {d['environment']['load_average_at_start']})\n")
        md.append("| dies | flows | extract (ms) | loads (ms) | full score median (ms) | p90 | incremental median (ms) | p90 | consistency | search steps | search (s) | full/incr |"); md.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in d["instances"]:
            md.append(f"| {r['n_dies']} | {r['n_flows']} | {r['traffic_extract']['median_ms']:.1f} | {r['loads_build']['median_ms']:.1f} | {r['full_score']['median_ms']:.1f} | {r['full_score']['p90_ms']:.1f} | "
                      f"{r['incremental_all']['median_ms']:.2f} | {r['incremental_all']['p90_ms']:.2f} | {r['consistency_max_rel_err']:.1e} | {r['search_steps']} | {r['search_wall_s']:.1f} | {r['full_over_incremental']:.0f} |")
        md.append("")
    # main-case candidates
    md.append("## Main-case candidates (automatic shortlist; measured accounts, kappa >= 2, seed range <= 1.5 points, sorted by G)\n")
    cand = [r for r in done if r["kappa"] >= 2 and r["G_range"] <= 1.5 and "measured" in r["account"] and r["unit"] != "confirm"
            and r["tiling"] != "row" and r["topology"] == "mesh" and r["L"] >= 8 and r["phase"] == "prefill" and r["S"] == 512
            and r["n_dies"] >= 400]      # corners (forced row split, ring, tiny depth) are listed apart; the main case is a sizeable mesh deployment
    cand = sorted(cand, key=lambda r: -r["G_median"])[:8]
    table("Shortlist", cand)
    common = sorted(done, key=lambda r: abs(r["G_median"] - statistics.median(x["G_median"] for x in done)))[:3] if done else []
    table("Common-condition cases (closest to the median gain)", common)
    corners = []
    for r in done:
        if r["kappa"] == 1 or r["G_median"] < 1 or r["tiling"] == "row" or r["topology"] == "ring":
            corners.append(r)
    table("Corner cases (port-bound kappa 1, near-zero gains, row-split tiling, ring)", sorted(corners, key=lambda r: r["G_median"])[:12])
    auto = [{k: r[k] for k in ("d", "dh", "d_ff", "L", "S", "phase", "tiling", "topology", "routing", "kappa", "bw")} | {"grid": [int(x) for x in r["grid"].split("x")], "model_tag": r["config_id"].split("_")[0]} for r in cand[:5]]
    json.dump(auto, open(os.path.join(V3, "confirm_specs_auto.json"), "w"), indent=1)
    if not os.path.exists(os.path.join(V3, "confirm_specs.json")):      # never overwrite a hand-edited list
        json.dump(auto, open(os.path.join(V3, "confirm_specs.json"), "w"), indent=1)
    md.append("\n## Figure data index\n")
    md.append("- Fig. 1 (envelopes): `all_configs.csv` columns B_minus, B_plus, band_ratio, band_ratio_pool per config; the full curves per config in each unit's configs.jsonl (`cost_grid`).\n- Fig. 2 (resource accounting example): `e3/library_mech4x4.json` candidates with flows.\n- Fig. 3 (validation, efficiency): `e3/discriminability.json`, `e3/candidates.csv`, `e5/timing.csv`.\n- Fig. 4 (main case): `confirm/` unit after confirmation; `candidates.csv`, `runs.csv` of that unit.\n- Fig. 5 (discriminability, ablation): `e3/library_*.json`, `e3/ablation_*.json`.\n- Fig. 6 (scaling and conditions): `e2_*/summary.csv`, `e1a/summary.csv`, `e1s/summary.csv`, `e4/summary.csv`, `e1t/summary.csv`, every unit's `cost_grid.csv`.\n")
    open(os.path.join(V3, "REPORT.md"), "w").write("\n".join(md))
    print("->", os.path.join(V3, "REPORT.md"), len(rows), "configs")


if __name__ == "__main__":
    main()
